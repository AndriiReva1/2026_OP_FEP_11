#include <stdio.h>

int main()
{
    // --- 1. Арифметичні оператори ---
    int a = 15;
    int b = 4;
    int res;

    // Змінні для демонстрації інкременту/декременту
    int post_inc = 5;
    int post_dec = 5;
    int pre_inc = 5;
    int pre_dec = 5;

    printf("=== АРИФМЕТИЧНІ ОПЕРАТОРИ ===\n");
    printf("Початкові числа: a = %d, b = %d\n\n", a, b);

    res = a + b;
    printf("Додавання (+):          %d + %d = %d\n", a, b, res);

    res = a - b;
    printf("Віднімання (-):         %d - %d = %d\n", a, b, res);

    res = a * b;
    printf("Множення (*):           %d * %d = %d\n", a, b, res);

    res = a / b;
    printf("Ділення стовпчиком (/): %d / %d = %d (ціла частина)\n", a, b, res);

    res = a % b;
    printf("Остача від ділення (%%): %d %% %d = %d\n\n", a, b, res);

    // Постфіксна форма: змінює значення ПІСЛЯ використання у рядку
    printf("Постфіксний інкремент:  5++    = %d (виводить старе 5, але в пам'яті вже 6)\n",
        post_inc++);
    printf("Значення після кроку:          = %d\n", post_inc);
    printf("Постфіксний декремент:  5--    = %d\n", post_dec--);
    printf("Значення після кроку:          = %d\n\n", post_dec);

    // Префіксна форма: змінює значення ДО виведення на екран
    printf("Префіксний інкремент:   ++5    = %d (одразу змінює і виводить 6)\n", ++pre_inc);
    printf("Префіксний декремент:   --5    = %d (одразу змінює і виводить 4)\n\n", --pre_dec);

    // --- 2. Логічні оператори ---
    int x = 1; // true (у мові C: все, що не 0)
    int y = 0; // false (у мові C: строго 0)

    printf("=== ЛОГІЧНІ ОПЕРАТОРИ ===\n");
    printf("Початкові значення: x = %d (true), y = %d (false)\n\n", x, y);

    printf("Логічне І (&&):         x && y = %d (false, бо одне з них 0)\n", x && y);
    printf("Логічне АБО (||):       x || y = %d (true, бо хоча б одне є 1)\n", x || y);
    printf("Логічне НЕ (!):         !x     = %d (перетворило 1 на 0)\n\n", !x);

    // --- 3. Побітові оператори (двійковий формат) ---
    unsigned int p = 12; // 12 у двійковій: 1100
    unsigned int q = 5;  // 5  у двійковій: 0101

    printf("=== ПОБІТОВІ ЛОГІЧНІ ОПЕРАЦІЇ (ДВІЙКОВИЙ ФОРМАТ) ===\n");
    printf("Число p: %12d  -->  в двійковій: %#b\n", p, p);
    printf("Число q: %12d  -->  в двійковій: %#b\n\n", q, q);

    printf("Побітове І (&):         p & q  -->  %#b\n", p & q);
    printf("Побітове АБО (|):       p | q  -->  %#b\n", p | q);
    printf("Виключне АБО (^):       p ^ q  -->  %#b\n", p ^ q);
    printf("Побітове НЕ (~):        ~p     -->  %#b (інверсія всіх бітів)\n", ~p);

    // Оператори зсуву бітів
    printf("Зсув ліворуч (<< 1):    p << 1 -->  %#b (число помножилося на 2)\n", p << 1);
    printf("Зсув праворуч (>> 1):   p >> 1 -->  %#b (число поділилося на 2)\n", p >> 1);

    return 0;
}
