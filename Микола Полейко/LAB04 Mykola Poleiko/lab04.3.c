#include <math.h> // потрібна для функції sqrt()
#include <stdio.h>

int main()
{
    double a, b, c; // коефіцієнти рівняння
    double d;       // дискримінант
    double x1, x2;  // корені рівняння

    printf("--- Розв'язання квадратного рівняння (ax^2 + bx + c = 0) ---\n");
    printf("Введіть коефіцієнти a, b, c (через пробіл): ");
    scanf("%lf %lf %lf", &a, &b, &c);

    // Перевірка, чи рівняння дійсно є квадратним
    if (a == 0) {
        printf("Помилка: коефіцієнт 'a' не може дорівнювати 0 (рівняння стає лінійним).\n");
        return 1;
    }

    d = b * b - 4 * a * c; // обчислення дискримінанту

    printf("\nДискримінант (D) = %.2f\n", d);

    // Аналіз дискримінанту за допомогою умовних операторів
    if (d > 0) {
        x1 = (-b + sqrt(d)) / (2 * a);
        x2 = (-b - sqrt(d)) / (2 * a);
        printf("Рівняння має два корені:\n");
        printf("x1 = %.4f\n", x1);
        printf("x2 = %.4f\n", x2);
    } else if (d == 0) {
        x1 = -b / (2 * a);
        printf("Рівняння має один корінь:\n");
        printf("x = %.4f\n", x1);
    } else {
        printf("Рівняння не має дійсних коренів (D < 0).\n");
    }

    return 0;
}
