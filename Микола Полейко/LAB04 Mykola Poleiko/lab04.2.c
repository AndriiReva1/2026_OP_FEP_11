#include <stdio.h>

int main()
{
    int  n; // звичайна змінна
    int* p; // змінна-вказівник

    printf("Введіть ціле число: ");
    scanf("%d", &n);

    p = &n; // оператор & бере адресу змінної n і передає її в p

    // *p (розіменування) дістає значення, яке лежить за адресою
    printf("\nЗначення через вказівник: %d\n", *p);

    // %p виводить саму адресу пам'яті у 16-ковому форматі
    printf("Адреса змінної в пам'яті: %p\n", (void*)p);

    return 0;
}
